function loadDatabase() {
  fs.mkdirSync(dataDirectory, { recursive: true });
  if (!fs.existsSync(databaseFile)) {
    fs.writeFileSync(databaseFile, JSON.stringify(initialDatabase, null, 2));
  }
  return JSON.parse(fs.readFileSync(databaseFile, "utf8"));
}

function saveDatabase(database) {
  fs.mkdirSync(dataDirectory, { recursive: true });
  const temporaryFile = `${databaseFile}.tmp`;
  fs.writeFileSync(temporaryFile, JSON.stringify(database, null, 2));
  fs.renameSync(temporaryFile, databaseFile);
}

function createLocalStore(database = loadDatabase(), persist = saveDatabase) {
  return {
    getFacilities: async () => database.facilities,
    getBookings: async () => database.bookings,
    createBooking: async (facility, date) => {
      const booking = {
        id:
          database.bookings.reduce(
            (maxId, item) => Math.max(maxId, item.id),
            0,
          ) + 1,
        facility,
        date,
      };
      database.bookings.push(booking);
      await persist(database);
      return booking;
    },
    deleteBooking: async (id) => {
      const before = database.bookings.length;
      database.bookings = database.bookings.filter(
        (booking) => booking.id !== id,
      );
      if (database.bookings.length === before) return false;
      await persist(database);
      return true;
    },
    getReports: async () => database.reports,
    createReport: async (facility, category, details) => {
      const report = {
        ticketId:
          10000 +
          database.reports.reduce(
            (maxId, item) => Math.max(maxId, item.ticketId - 10000),
            0,
          ) +
          1,
        facility,
        category,
        details,
        createdAt: new Date().toISOString(),
      };
      database.reports.push(report);
      await persist(database);
      return report;
    },
  };
}

async function createNeonStore(connectionString) {
  const { neon } = await import("@neondatabase/serverless");
  const sql = neon(connectionString);

  await sql`CREATE TABLE IF NOT EXISTS coastlink_bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facility TEXT NOT NULL,
    date DATE NOT NULL
  )`;
  await sql`CREATE TABLE IF NOT EXISTS coastlink_reports (
    ticket_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 10001) PRIMARY KEY,
    facility TEXT NOT NULL,
    category TEXT NOT NULL,
    details TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  )`;
  const initialBooking = initialDatabase.bookings[0];
  await sql`INSERT INTO coastlink_bookings (facility, date)
    SELECT ${initialBooking.facility}, ${initialBooking.date}
    WHERE NOT EXISTS (SELECT 1 FROM coastlink_bookings)`;

  return {
    getFacilities: async () => initialDatabase.facilities,
    getBookings: async () => {
      const rows =
        await sql`SELECT id, facility, to_char(date, 'YYYY-MM-DD') AS date
        FROM coastlink_bookings ORDER BY id`;
      return rows.map((row) => ({ ...row, id: Number(row.id) }));
    },
    createBooking: async (facility, date) => {
      const [booking] =
        await sql`INSERT INTO coastlink_bookings (facility, date)
        VALUES (${facility}, ${date}) RETURNING id, facility, to_char(date, 'YYYY-MM-DD') AS date`;
      return { ...booking, id: Number(booking.id) };
    },
    deleteBooking: async (id) => {
      const rows =
        await sql`DELETE FROM coastlink_bookings WHERE id = ${id} RETURNING id`;
      return rows.length > 0;
    },
    getReports: async () => {
      const rows =
        await sql`SELECT ticket_id, facility, category, details, created_at
        FROM coastlink_reports ORDER BY ticket_id`;
      return rows.map((row) => ({
        ticketId: Number(row.ticket_id),
        facility: row.facility,
        category: row.category,
        details: row.details,
        createdAt: row.created_at,
      }));
    },
    createReport: async (facility, category, details) => {
      const [report] =
        await sql`INSERT INTO coastlink_reports (facility, category, details)
        VALUES (${facility}, ${category}, ${details})
        RETURNING ticket_id, facility, category, details, created_at`;
      return {
        ticketId: Number(report.ticket_id),
        facility: report.facility,
        category: report.category,
        details: report.details,
        createdAt: report.created_at,
      };
    },
  };
}

function createStore(options = {}) {
  if (process.env.DATABASE_URL)
    return createNeonStore(process.env.DATABASE_URL);
  if (process.env.VERCEL) {
    throw new Error("DATABASE_URL must be configured for Vercel deployments");
  }
  return Promise.resolve(
    createLocalStore(
      options.database || loadDatabase(),
      options.persist || saveDatabase,
    ),
  );
}

